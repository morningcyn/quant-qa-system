# 生成 3 条样例对话（高分 / 中分 / 低分-黄灯）到 samples/ 目录，供验收与演示。
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "samples"

HIGH = """[客] 你好，我之前买的科技主题基金最近回调挺多的，心里有点没底。
[助] 王先生您好，我先帮您看一下持仓的具体情况。您最近这笔基金的回撤主要是科技板块整体调整带动的，不是产品本身出了问题。
[客] 我看账户里已经浮亏8个点了，是不是该先卖了？
[助] 我理解您的担心，浮亏的时候最难受的就是不知道该不该动。咱们先不着急做决定，我帮您梳理一下：第一，这只基金的前十大重仓里没有出现基本面恶化的品种；第二，它的回撤幅度和同类产品比处于中位水平。您当初买它主要是看重科技成长的长期逻辑，这个逻辑目前并没有被破坏。
[客] 那您觉得现在应该怎么办？
[助] 我给您的建议是：仓位暂时不动，再观察两周。我会每周三收盘后帮您更新一次净值与板块资金流向，如果单周回撤再扩大超过3个点，我会第一时间联系您一起商量是否减仓。您看这样安排可以吗？
[客] 可以，那麻烦您了。
[助] 不麻烦，这是应该做的。另外提醒您，这笔钱如果短期内有使用计划，我们也可以先赎回一部分留足流动性，您家庭近期有大额支出安排吗？
[客] 暂时没有，先放着吧。
[助] 好的，那就按刚才的方案执行：本周三我会主动给您发一次复盘，有异动随时联系。您还有其他想了解的吗？
[客] 没有了，谢谢。
[助] 不客气，祝您生活愉快！"""

MID = """[客] 你好，我买的基金一直跌，怎么办？
[助] 您好，市场最近波动确实比较大，您持有的产品也跟着回调了。
[客] 已经亏了快15个点了，天天看盘睡不着觉。
[助] 我理解您的心情，不过基金投资要看长期，短期波动是正常的，建议您先拿着。
[客] 那要等到什么时候才能回本？
[助] 这个要看市场情况，具体时间不好说。建议您拉长投资周期，用时间换空间。
[客] 我现在要不要补点仓摊低成本？
[助] 补仓的话要看您的资金情况，如果是不着急用的钱可以适当分批补。
[客] 好的，那我再想想。
[助] 好的，有问题随时找我。"""

LOW = """[客] 我买的基金亏了好多，到底怎么回事？
[助] 行情就这样，谁也没办法。
[客] 我已经亏了20个点了，天天睡不着，你们当初不是说这个产品很稳吗？
[助] 当时推荐的时候市场好，现在跌了也不能怪我们吧。
[客] 那我现在怎么办？割肉吗？
[助] 这个你自己决定，卖了可能就割在地板上，拿着可能继续跌。
[客] 你们就是这样服务客户的？
[助] 我们也没办法，大盘跌成这样，所有产品都在跌，建议您别看盘了。
[客] 那我的钱什么时候能回来？
[助] 不知道，等行情好起来吧。
[客] 算了，就当我倒霉。
[助] 好的，有需要再联系。"""

SAMPLES = {
    "sample_high.txt": HIGH,
    "sample_mid.txt": MID,
    "sample_low.txt": LOW,
}


def main() -> int:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for name, text in SAMPLES.items():
        (OUT_DIR / name).write_text(text, encoding="utf-8")
        print(f"[OK] {OUT_DIR / name}  （{len(text)} 字）")
    print("\n用法：在应用中新建员工后，「上传会话质检」选择这些 txt 文件。")
    print("预期：high ≥ 75 分正常；mid 60~75 分；low < 59 分触发黄灯预警。")
    return 0


if __name__ == "__main__":
    sys.exit(main())
