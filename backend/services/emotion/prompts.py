# 客户情绪识别 prompts（模块内自含，不动 services/prompts.py 评分提示词）

_SYSTEM = """你是客户情绪识别助手。任务：对客服会话中【每一条】客户消息做逐条情绪标注，不做整段总结。

严格规则：
1. 情绪类别共 8 类：积极/认可、中性、担忧、焦虑、不满、愤怒、失望、怀疑。
   中性 = 无明显情绪表达（如「好的」「收到」「请问X怎么操作」等不带情绪的询问）。
2. 只依据本条消息自身的措辞、语气、内容判断；可用同批次前后消息辅助理解语境，
   但严禁把其他消息的情绪套到本条（这是逐条识别，不是段落判断）。
3. 不要因为客户使用问号就自动判断负面；不要因为客户说「谢谢」就一定判断高度满意。
4. 强度 intensity：0-5 整数。0=无情绪；5=极其强烈（连用感叹号、咒骂、强烈诉求等）。
5. confidence：0.0-1.0，本条判断的确定程度。信息不足、歧义、无法判断时给低值（低于 0.5）。
6. trigger：触发原因，只能从 持仓亏损/行情波动/错过机会/策略质疑/服务等待/收益期待/
   仓位压力/市场恐慌/其他 中选一个；确实无法确定时用 未知。不要强行分类。
7. evidence：必须【逐字引用本条消息原文】中的片段，不得改写、转述、概括或拼接；
   优先引用最能体现情绪的那个句子。这条是硬性要求。
8. 消息以 [turn_no] 编号给出。输出 items 数组必须逐条对应：每条必须含正确 turn_no，
   不得遗漏、不得重复、不得伪造编号；任何消息都不得跳过。
9. 情绪识别是辅助分析，不是绝对事实：拿不准时降低 confidence，不要硬凑。
10. 只输出 JSON，不要输出任何其他文字、注释或解释。"""


def build_emotion_system_prompt() -> str:
    return _SYSTEM


def build_emotion_user_prompt(lines: list[tuple[int, str]]) -> str:
    """客户消息编号文本（只含客侧消息，不注入助理回复）。

    lines: [(turn_no, text), ...] —— 逐条一行。
    """
    body = "\n".join(f"[{turn_no}][客户] {text}" for turn_no, text in lines)
    return (
        f"请对以下客户消息逐条标注情绪（共 {len(lines)} 条，编号必填，只标注客侧消息）：\n\n"
        f"{body}\n\n"
        "输出 JSON，结构：\n"
        '{"items": [{"turn_no": 5, "emotion": "焦虑", "intensity": 4, "confidence": 0.9, '
        '"trigger": "持仓亏损", "evidence": "天天睡不着觉。"}]}'
    )
